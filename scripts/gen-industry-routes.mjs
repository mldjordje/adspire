#!/usr/bin/env node
/**
 * Generates one route file per industry page.
 *
 * These pages want root URLs with the keyword in them (/softver-za-stomatolosku-
 * ordinaciju), which is the strongest URL shape we have and matches the five
 * existing niche pages. A dynamic root segment would have been less typing, but
 * src/app/[locale] already owns the root dynamic slot and Next refuses a second
 * slug name at the same level.
 *
 * So the files are generated instead of written by hand. Every one is the same
 * seventeen lines; the content lives in src/content/site/industries. A test
 * fails if the registry and the folders drift apart.
 *
 *   node scripts/gen-industry-routes.mjs          write missing routes
 *   node scripts/gen-industry-routes.mjs --check  exit 1 if anything is missing
 */

import { readdirSync, readFileSync, writeFileSync, mkdirSync, existsSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const contentDir = join(root, "src", "content", "site", "industries");
const appDir = join(root, "src", "app");

const SKIP = new Set(["index.ts", "types.ts", "proof.ts"]);

/** Slugs, read straight out of the content files — no TS runtime needed. */
function readSlugs() {
  const slugs = [];
  for (const file of readdirSync(contentDir)) {
    if (!file.endsWith(".ts") || SKIP.has(file)) continue;
    const source = readFileSync(join(contentDir, file), "utf8");
    const match = source.match(/^\s*slug:\s*"([^"]+)"/m);
    if (!match) {
      console.error(`× ${file}: nema slug polja`);
      process.exitCode = 1;
      continue;
    }
    slugs.push({ slug: match[1], file });
  }
  return slugs;
}

function routeSource(slug) {
  return `import { JsonLd } from "@/components/site/JsonLd";
import { IndustryV4 } from "@/components/site/v4/IndustryV4";
import { v4FontClass } from "@/components/site/v4/fonts";
import { industryJsonLd, industryMetadata, industryPageBySlug } from "@/lib/seo/industries";

// Generated by scripts/gen-industry-routes.mjs — edit the content file instead.
const page = industryPageBySlug("${slug}");

export const metadata = industryMetadata(page);

export default function Page() {
  return (
    <div className={v4FontClass}>
      <JsonLd data={industryJsonLd(page)} />
      <IndustryV4 page={page} />
    </div>
  );
}
`;
}

const check = process.argv.includes("--check");
let missing = 0;
let written = 0;

for (const { slug, file } of readSlugs()) {
  const dir = join(appDir, slug);
  const target = join(dir, "page.tsx");
  const wanted = routeSource(slug);

  if (existsSync(target) && readFileSync(target, "utf8") === wanted) continue;

  if (check) {
    console.error(`× /${slug} (${file}): ruta nedostaje ili nije u koraku`);
    missing += 1;
    continue;
  }

  mkdirSync(dir, { recursive: true });
  writeFileSync(target, wanted, "utf8");
  console.log(`✓ /${slug}`);
  written += 1;
}

if (check && missing) {
  console.error(`\n${missing} ruta nije generisano. Pokrenite: npm run gen:industries`);
  process.exit(1);
}

if (!check) console.log(written ? `\n${written} ruta upisano.` : "\nSve rute su već u koraku.");
